<h1>Часто задаваемые вопросы</h1>
<h2>Общие вопросы</h2>

<div class="faq-item">
    <h3>Что такое Non-lossing Play?</h3>
    <p>Non-lossing Play - это учебный проект, созданный для демонстрации возможностей веб-разработки. Это не реальный игровой сайт.</p>
</div>

<div class="faq-item">
    <h3>Могу ли я играть здесь на реальные деньги?</h3>
    <p>Нет, это исключительно учебный проект. Все игровые элементы являются демонстрационными и не предполагают использование реальных денег.</p>
</div>

<div class="faq-item">
    <h3>Нужно ли регистрироваться для использования сайта?</h3>
    <p>Нет, регистрация не требуется, так как это учебный проект с демонстрационным функционалом.</p>
</div>

<h2 id="solutions">Решения проблем</h2>

<div class="faq-item">
    <h3>Сайт отображается некорректно. Что делать?</h3>
    <p>1. Проверьте, используете ли вы современный браузер (Chrome, Firefox, Safari, Edge)<br>
    2. Очистите кэш браузера<br>
    3. Проверьте подключение к интернету</p>
</div>

<div class="faq-item">
    <h3>Не работают некоторые функции сайта</h3>
    <p>Поскольку это учебный проект, некоторые функции могут быть не реализованы полностью или быть в демонстрационном режиме.</p>
</div>

<div class="faq-item">
    <h3>Как сообщить об ошибке?</h3>
    <p>Вы можете отправить описание ошибки на email: support@non-lossing-play.edu</p>
</div>

