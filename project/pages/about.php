<h1>О проекте Non-lossing Play</h1>
<p>Non-lossing Play - это учебный проект, разработанный для демонстрации возможностей веб-разработки и дизайна.</p>

<h2 id="mission">Наша миссия</h2>
<p>Наша миссия - создавать качественные учебные материалы и проекты, которые помогают начинающим разработчикам освоить современные технологии веб-разработки.</p>

<h2>Цели проекта</h2>
<ul>
    <li>Предоставить наглядный пример реализации многостраничного сайта</li>
    <li>Продемонстрировать использование PHP для шаблонизации</li>
    <li>Создать адаптивный дизайн, работающий на различных устройствах</li>
    <li>Обеспечить чистую и понятную структуру кода для обучения</li>
</ul>

<h2>Технологии</h2>
<p>В проекте используются современные веб-технологии:</p>
<ul>
    <li>HTML5 для структуры страниц</li>
    <li>CSS3 для стилизации и адаптивного дизайна</li>
    <li>PHP для шаблонизации и разделения кода</li>
    <li>JavaScript для интерактивных элементов (в будущем)</li>
</ul>